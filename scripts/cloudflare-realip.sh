#!/usr/bin/env bash
# Print an nginx snippet that restores real visitor IPs when Cloudflare's proxy (orange cloud) is in front.
# Without it, nginx and Posthouse see Cloudflare's addresses, and the password rate limit would treat
# many visitors as one.
#
#   scripts/cloudflare-realip.sh | sudo tee /etc/nginx/conf.d/cloudflare-realip.conf
#   sudo nginx -t && sudo systemctl reload nginx
#
# Re-run it now and then (e.g. monthly from cron): Cloudflare occasionally adds address ranges.
set -euo pipefail

fetch() {
  curl -fsS --max-time 20 "$1" || { echo "Could not download $1" >&2; exit 1; }
}

v4="$(fetch https://www.cloudflare.com/ips-v4)"
v6="$(fetch https://www.cloudflare.com/ips-v6)"

echo "# Cloudflare edge ranges, generated by posthouse/scripts/cloudflare-realip.sh on $(date -u +%Y-%m-%d)."
echo "# Must be inside the http {} context (files in /etc/nginx/conf.d/ usually are)."
count=0
for range in $v4 $v6; do
  # accept only things that look like CIDR ranges
  if [[ "$range" =~ ^[0-9a-fA-F:.]+/[0-9]{1,3}$ ]]; then
    echo "set_real_ip_from $range;"
    count=$((count + 1))
  fi
done
[ "$count" -gt 0 ] || { echo "No address ranges found in Cloudflare's lists." >&2; exit 1; }
echo "real_ip_header CF-Connecting-IP;"
